//! Generates Rust from the design sheets (../../sheets/*.json): one struct literal per row.
//! The sheets are the source of truth; a missing sheet, column or cross-sheet id fails the build.

use serde_json::Value;
use std::collections::HashSet;
use std::fmt::Write;

fn load(name: &str) -> Value {
    let path = format!("../../sheets/{name}.json");
    println!("cargo:rerun-if-changed={path}");
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{path}: {e}"))
}

fn rows(v: &Value) -> &Vec<Value> {
    v["rows"].as_array().expect("rows")
}

fn ids(v: &Value) -> HashSet<String> {
    rows(v).iter().map(|r| r["id"].as_str().unwrap().to_string()).collect()
}

fn s(r: &Value, c: &str) -> String {
    match &r[c] {
        Value::String(x) => format!("{x:?}"),
        other => panic!("{}.{c}: expected text, got {other}", r["id"]),
    }
}

fn opt_s(r: &Value, c: &str) -> String {
    match &r[c] {
        Value::Null => "None".into(),
        Value::String(x) if x == "none" => "None".into(),
        Value::String(x) => format!("Some({x:?})"),
        other => panic!("{}.{c}: expected text or null, got {other}", r["id"]),
    }
}

fn f(r: &Value, c: &str) -> String {
    let x = r[c].as_f64().unwrap_or_else(|| panic!("{}.{c}: expected number", r["id"]));
    format!("{x:?}f32")
}

fn i(r: &Value, c: &str) -> String {
    r[c].as_i64().unwrap_or_else(|| panic!("{}.{c}: expected integer", r["id"])).to_string()
}

fn opt_i(r: &Value, c: &str) -> String {
    match r[c].as_i64() {
        Some(x) => format!("Some({x})"),
        None => "None".into(),
    }
}

fn b(r: &Value, c: &str) -> String {
    r[c].as_bool().unwrap_or_else(|| panic!("{}.{c}: expected true/false", r["id"])).to_string()
}

fn camel(id: &str) -> String {
    id.split('_').map(|p| p[..1].to_uppercase() + &p[1..]).collect()
}

fn must(set: &HashSet<String>, sheet: &str, id: &str, from: &str) {
    if !set.contains(id) {
        panic!("{from} -> {sheet}.{id} does not exist");
    }
}

fn main() {
    let deliveries = load("deliveries");
    let abilities = load("abilities");
    let fighters = load("fighters");
    let profiles = load("stat_profiles");
    let audio = load("audio");
    let (d_ids, a_ids, f_ids, p_ids, au_ids) =
        (ids(&deliveries), ids(&abilities), ids(&fighters), ids(&profiles), ids(&audio));

    let mut o = String::new();
    writeln!(o, "// @generated by build.rs from sheets/*.json. Edit the sheets, not this file.\n").unwrap();

    // deliveries -> enum
    writeln!(o, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Delivery {{").unwrap();
    for r in rows(&deliveries) {
        writeln!(o, "    {},", camel(r["id"].as_str().unwrap())).unwrap();
    }
    writeln!(o, "}}\n").unwrap();
    writeln!(o, "impl Delivery {{\n    pub fn hits_per_cast(self) -> f32 {{\n        match self {{").unwrap();
    for r in rows(&deliveries) {
        writeln!(o, "            Delivery::{} => {}.0,", camel(r["id"].as_str().unwrap()), i(r, "hits_per_cast")).unwrap();
    }
    writeln!(o, "        }}\n    }}\n    pub fn streams(self) -> u32 {{\n        match self {{").unwrap();
    for r in rows(&deliveries) {
        writeln!(o, "            Delivery::{} => {},", camel(r["id"].as_str().unwrap()), i(r, "streams")).unwrap();
    }
    writeln!(o, "        }}\n    }}\n}}\n").unwrap();

    // stat profiles
    writeln!(o, "pub static STAT_PROFILES: &[StatProfile] = &[").unwrap();
    for r in rows(&profiles) {
        writeln!(o, "    StatProfile {{ id: {}, hp_mult: {}, fp_mult: {}, stamina_mult: {}, damage_taken_mult: {}, ki_regen_per_s: {}, er_speffect: {} }},",
            s(r, "id"), f(r, "hp_mult"), f(r, "fp_mult"), f(r, "stamina_mult"),
            f(r, "damage_taken_mult"), f(r, "ki_regen_per_s"), opt_i(r, "er_speffect")).unwrap();
    }
    writeln!(o, "];\n").unwrap();

    // audio
    writeln!(o, "pub static AUDIO: &[AudioRow] = &[").unwrap();
    for r in rows(&audio) {
        let fid = r["fighter"].as_str().unwrap();
        if fid != "none" {
            must(&f_ids, "fighters", fid, &format!("audio.{}", r["id"]));
        }
        let pick = match &r["stream"] {
            Value::String(x) if x == "random" => "AudioPick::Random".to_string(),
            Value::Number(n) => format!("AudioPick::Index({})", n.as_u64().unwrap() - 1),
            _ => "AudioPick::Unset".to_string(),
        };
        writeln!(o, "    AudioRow {{ id: {}, bank: {}, pick: {pick}, fighter: {} }},", s(r, "id"), s(r, "bank"), opt_s(r, "fighter")).unwrap();
    }
    writeln!(o, "];\n").unwrap();

    // abilities
    writeln!(o, "pub static ABILITIES: &[Ability] = &[").unwrap();
    for r in rows(&abilities) {
        let id = r["id"].as_str().unwrap();
        let d = r["delivery"].as_str().unwrap();
        must(&d_ids, "deliveries", d, &format!("abilities.{id}"));
        let owner = r["owner"].as_str().unwrap();
        if owner != "avatar" {
            must(&f_ids, "fighters", owner, &format!("abilities.{id}"));
        }
        let slot = if r["slot"] == "ultimate" { "Slot::Ultimate" } else { "Slot::Skill" };
        writeln!(o, "    Ability {{ id: {}, name: {}, owner: {}, slot: {slot}, delivery: Delivery::{}, element: {}, dmg_mult: {}, fp_cost: {}, cooldown_s: {}, range_m: {}, charge: {}, er_anim: {}, er_bullet: {}, creator_pool: {}, charge_s: {}, kind: Kind::{}, hits: {}, combo: {} }},",
            s(r, "id"), s(r, "name"), s(r, "owner"), camel(d), s(r, "element"), f(r, "dmg_mult"), i(r, "fp_cost"),
            f(r, "cooldown_s"), f(r, "range_m"), b(r, "charge"), opt_i(r, "er_anim"), i(r, "er_bullet"), b(r, "creator_pool"), f(r, "charge_s"), camel(r["kind"].as_str().expect("abilities.kind")), f(r, "hits"), b(r, "combo")).unwrap();
    }
    writeln!(o, "];\n").unwrap();

    // inputs
    let inputs = load("inputs");
    writeln!(o, "pub static INPUTS: &[InputRow] = &[").unwrap();
    for r in rows(&inputs) {
        let kb = r["keyboard"].as_str().unwrap();
        let kb = i32::from_str_radix(kb.trim_start_matches("0x"), 16).unwrap_or_else(|_| panic!("inputs.{}.keyboard", r["id"]));
        let mut mask = 0u16;
        for b in r["controller"].as_str().unwrap().split('+') {
            mask |= match b {
                "DPAD_UP" => 0x0001, "DPAD_DOWN" => 0x0002, "DPAD_LEFT" => 0x0004, "DPAD_RIGHT" => 0x0008,
                "START" => 0x0010, "BACK" => 0x0020, "LEFT_THUMB" => 0x0040, "RIGHT_THUMB" => 0x0080,
                "LEFT_SHOULDER" => 0x0100, "RIGHT_SHOULDER" => 0x0200,
                "LEFT_TRIGGER" => 0x0400, "RIGHT_TRIGGER" => 0x0800,
                "A" => 0x1000, "B" => 0x2000, "X" => 0x4000, "Y" => 0x8000,
                other => panic!("inputs.{}.controller: unknown button {other}", r["id"]),
            };
        }
        let when = match r["when"].as_str().unwrap() {
            "in_world" => "When::InWorld", "grace" => "When::Grace", "menu" => "When::Menu",
            other => panic!("inputs.{}.when: {other}", r["id"]),
        };
        writeln!(o, "    InputRow {{ id: {}, keyboard: {kb:#x}, controller: {mask:#06x}, when: {when} }},", s(r, "id")).unwrap();
    }
    writeln!(o, "];\n").unwrap();

    // fighters
    writeln!(o, "pub static FIGHTERS: &[Fighter] = &[").unwrap();
    for r in rows(&fighters) {
        let id = r["id"].as_str().unwrap();
        let abil: Vec<String> = r["abilities"].as_array().unwrap().iter().map(|a| {
            let a = a.as_str().unwrap();
            if a != "$loadout" {
                must(&a_ids, "abilities", a, &format!("fighters.{id}"));
            }
            format!("{a:?}")
        }).collect();
        let p = r["stat_profile"].as_str().unwrap();
        must(&p_ids, "stat_profiles", p, &format!("fighters.{id}"));
        let voice = rows(&audio).iter()
            .find(|a| a["fighter"] == id)
            .map(|a| format!("Some({:?})", a["id"].as_str().unwrap()))
            .unwrap_or_else(|| "None".into());
        let outfit = match &r["outfit"] {
            Value::Array(a) => format!("Some([{}])", a.iter().map(|v| v.as_i64().unwrap_or_else(|| panic!("fighters.{id}.outfit")).to_string()).collect::<Vec<_>>().join(", ")),
            Value::String(s) if s == "$player" => "None".into(),
            other => panic!("fighters.{id}.outfit: {other}"),
        };
        // Look columns: a list of numbers, null (not picked yet) or "$player" (own look) -> Option.
        let nums = |c: &str, n: usize| -> String {
            match &r[c] {
                Value::Array(a) => {
                    assert_eq!(a.len(), n, "fighters.{id}.{c}: expected {n} numbers");
                    format!("Some([{}])", a.iter().map(|v| v.as_u64().unwrap_or_else(|| panic!("fighters.{id}.{c}")).to_string()).collect::<Vec<_>>().join(", "))
                }
                _ => "None".into(),
            }
        };
        let recolor = match &r["recolor"] {
            Value::Array(a) => format!("Some([{}])", a.iter().map(|p| match p {
                Value::Array(c) => format!("Some([{}])", c.iter().map(|v| v.as_u64().unwrap().to_string()).collect::<Vec<_>>().join(", ")),
                _ => "None".into(),
            }).collect::<Vec<_>>().join(", ")),
            _ => "None".into(),
        };
        let skin = match &r["skin"] {
            Value::Array(a) => format!("Some([{}])", a.iter().map(|p| match p {
                Value::String(n) => format!("Some({n:?})"),
                _ => "None".into(),
            }).collect::<Vec<_>>().join(", ")),
            _ => "None".into(),
        };
        let hair_model = r["hair_model"].as_u64().map(|v| format!("Some({v})")).unwrap_or_else(|| "None".into());
        let move_weapon = r["move_weapon"].as_u64().map(|v| format!("Some({v})")).unwrap_or_else(|| "None".into());
        let air_dash = s(r, "air_dash");
        assert!(air_dash == "\"fly\"" || air_dash == "\"dash\"", "{}.air_dash: fly or dash", r["id"]);
        writeln!(o, "    Fighter {{ id: {}, name: {}, series: {}, jf_dlc: {}, abilities: [{}], awakening: {}, stat_profile: {}, voice: {voice}, outfit: {outfit}, recolor: {recolor}, skin: {skin}, hair_model: {hair_model}, hair_rgb: {}, skin_rgb: {}, body: {}, height: {}, aura_speffect: {}, passive: {}, bare_hands: {}, move_weapon: {move_weapon}, flies: {}, particles: {} }},",
            s(r, "id"), s(r, "name"), s(r, "series"), b(r, "jf_dlc"), abil.join(", "), opt_s(r, "awakening"), s(r, "stat_profile"),
            nums("hair_rgb", 3), nums("skin_rgb", 3), nums("body", 5), f(r, "height"), i(r, "aura_speffect"), opt_s(r, "passive"), b(r, "bare_hands"), air_dash == "\"fly\"", opt_s(r, "particles")).unwrap();
    }
    writeln!(o, "];").unwrap();

    // Elden Force's own animations (only what the DLL needs to pick them; the poses are in anims.bin)
    let anims = load("anims");
    writeln!(o, "pub static ANIMS: &[AnimRow] = &[").unwrap();
    for (name, a) in anims["anims"].as_object().expect("anims") {
        let id = a["id"].as_u64().unwrap_or_else(|| panic!("anims.{name}.id"));
        let cue = a["cue"].as_str().unwrap_or_else(|| panic!("anims.{name}.cue"));
        let swing = matches!(cue, "Strike" | "Strike2" | "Heavy");
        writeln!(o, "    AnimRow {{ id: {id}, cue: {cue:?}, weapon_swing: {swing} }},").unwrap();
    }
    writeln!(o, "];").unwrap();

    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("sheets.rs");
    std::fs::write(out, o).unwrap();
}
